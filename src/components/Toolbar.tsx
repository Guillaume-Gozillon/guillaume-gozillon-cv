import { cv, type Contact } from '../data/cv'
import { cx } from '../lib/cx'
import { linkTargetProps } from '../lib/links'
import { PDF_FILENAME } from '../pdf.ts'
import { GithubIcon, LinkedinIcon, MailIcon, WebsiteIcon } from './icons'

const pdfUrl = `${import.meta.env.BASE_URL}${PDF_FILENAME}`

/** Links shown next to the download button, in this order; their URLs come from `cv.contacts` */
const profileLinks: {
  contact: Contact['icon']
  label: string
  Icon: typeof MailIcon
}[] = [
  { contact: 'website', label: 'Site web', Icon: WebsiteIcon },
  { contact: 'linkedin', label: 'LinkedIn', Icon: LinkedinIcon },
  { contact: 'github', label: 'GitHub', Icon: GithubIcon },
  { contact: 'mail', label: 'Me contacter', Icon: MailIcon }
]

const button =
  'flex h-28 items-center rounded-full text-base font-semibold shadow-sheet transition'

/** Download button, then links to the website, networks and e-mail (screen only) */
export function Toolbar({ className }: { className?: string }) {
  return (
    <nav
      aria-label='Liens'
      className={cx(
        'flex flex-wrap justify-center gap-6 px-12 max-md:gap-4',
        className
      )}
    >
      <a
        href={pdfUrl}
        download
        onClick={event => {
          // The PDF is only generated by `pnpm build`: in dev, open the print dialog instead
          if (import.meta.env.DEV) {
            event.preventDefault()
            window.print()
          }
        }}
        className={cx(
          button,
          'bg-brand-96 px-16 text-tint hover:brightness-110'
        )}
      >
        Télécharger en PDF
      </a>

      {profileLinks.map(({ contact, label, Icon }) => {
        const href = cv.contacts.find(({ icon }) => icon === contact)?.href
        return (
          href && (
            <a
              key={contact}
              href={href}
              {...linkTargetProps(href)}
              className={cx(
                button,
                'gap-5 bg-white px-12 text-primary-dark hover:bg-tint max-md:w-28 max-md:justify-center max-md:px-0'
              )}
            >
              <Icon className='size-12 shrink-0 text-primary' />
              {/* Icons only on phones, so the buttons fit on one line */}
              <span className='max-md:sr-only'>{label}</span>
            </a>
          )
        )
      })}
    </nav>
  )
}
