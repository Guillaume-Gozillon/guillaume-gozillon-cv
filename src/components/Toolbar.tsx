import { cv, lang, type Contact, type Lang } from '../data/cv'
import { cx } from '../lib/cx'
import { linkTargetProps } from '../lib/links'
import { notifyDownload } from '../lib/notifyDownload'
import { PAGE_PATHS, PDF_FILENAMES } from '../versions.ts'
import {
  DownloadIcon,
  GithubIcon,
  LanguageIcon,
  LinkedinIcon,
  MailIcon,
  WebsiteIcon
} from './icons'

const pdfUrl = `${import.meta.env.BASE_URL}${PDF_FILENAMES[lang]}`

const otherLang: Lang = lang === 'fr' ? 'en' : 'fr'
const otherLangUrl = `${import.meta.env.BASE_URL}${PAGE_PATHS[otherLang]}`

/** Links shown after the download button, in this order; their URLs come from `cv.contacts` */
const profileLinks: {
  contact: Contact['icon']
  label: string
  Icon: typeof MailIcon
}[] = [
  { contact: 'website', label: cv.labels.website, Icon: WebsiteIcon },
  { contact: 'linkedin', label: 'LinkedIn', Icon: LinkedinIcon },
  { contact: 'github', label: 'GitHub', Icon: GithubIcon },
  { contact: 'mail', label: cv.labels.contactMe, Icon: MailIcon }
]

const button =
  'flex h-28 items-center gap-5 rounded-full text-base font-semibold shadow-sheet transition'

/** Icon and label, then a round button on phones so that all the buttons fit on one line */
const secondaryButton = cx(
  button,
  'bg-white px-12 text-primary-dark hover:bg-tint max-md:w-28 max-md:justify-center max-md:px-0'
)

/** Download button, links to the website, networks and e-mail, then the other language (screen only) */
export function Toolbar({ className }: { className?: string }) {
  return (
    <nav
      aria-label={cv.labels.links}
      className={cx(
        'flex flex-wrap justify-center gap-6 px-12 max-md:gap-4',
        className
      )}
    >
      <a
        href={pdfUrl}
        download
        aria-label={cv.labels.download}
        onClick={event => {
          // The PDF is only generated by `pnpm build`: in dev, open the print dialog instead
          if (import.meta.env.DEV) {
            event.preventDefault()
            window.print()
          } else {
            void notifyDownload()
          }
        }}
        className={cx(
          button,
          'bg-brand-96 px-16 text-tint hover:brightness-110'
        )}
      >
        {/* Shorter on phones */}
        <DownloadIcon className='size-12 shrink-0 md:hidden' />
        <span className='max-md:hidden'>{cv.labels.download}</span>
        <span className='md:hidden'>PDF</span>
      </a>

      {profileLinks.map(({ contact, label, Icon }) => {
        const href = cv.contacts.find(({ icon }) => icon === contact)?.href
        return (
          href && (
            <a
              key={contact}
              href={href}
              {...linkTargetProps(href)}
              className={secondaryButton}
            >
              <Icon className='size-12 shrink-0 text-primary' />
              <span className='max-md:sr-only'>{label}</span>
            </a>
          )
        )
      })}

      <a
        href={otherLangUrl}
        hrefLang={otherLang}
        lang={otherLang}
        aria-label={cv.labels.otherLanguage}
        className={secondaryButton}
      >
        <LanguageIcon className='size-12 shrink-0 text-primary max-md:hidden' />
        <span className='max-md:hidden'>{cv.labels.otherLanguage}</span>
        <span className='md:hidden'>{otherLang.toUpperCase()}</span>
      </a>
    </nav>
  )
}
